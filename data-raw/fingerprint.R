# Fingerprints of the exemplar data sets, used by tests/testthat/test-data.R.
#
# A fingerprint is a platform-independent summary of a data set: its shape, the
# name and class of every column, and per column the number of missing values and
# a checksum (the sum of a numeric column; the number of distinct values and the
# total length of the text of any other column). It is deliberately not a hash of
# the serialised object, which can differ between R versions and platforms.
#
# Run from the package root after any change to the data to refresh the golden
# values, and review the diff: a changed fingerprint is a changed data set.
#   Rscript data-raw/fingerprint.R

fingerprint <- function(x) {
  x <- as.data.frame(x)
  cols <- lapply(x, function(v) {
    out <- list(class = class(v)[1], na = sum(is.na(v)))
    if (is.numeric(v)) {
      out$checksum <- round(sum(as.numeric(v), na.rm = TRUE), 4)
    } else {
      v <- as.character(v)
      out$checksum <- c(distinct = length(unique(v[!is.na(v)])), nchar = sum(nchar(v), na.rm = TRUE))
    }
    out
  })
  list(nrow = nrow(x), ncol = ncol(x), columns = cols)
}

if (sys.nframe() == 0L) {
  stopifnot(file.exists("DESCRIPTION"), requireNamespace("pkgload", quietly = TRUE))
  pkgload::load_all(".", quiet = TRUE)
  sets <- c("sgpData", "sgpData_LONG", "sgpData_LONG_COVID", "sgptData_LONG", "sgpData_INSTRUCTOR_NUMBER")
  golden <- setNames(lapply(sets, function(nm) fingerprint(get(nm))), sets)
  out <- c(
    "# Generated by data-raw/fingerprint.R. Do not edit by hand.",
    paste0("golden_fingerprints <- ", paste(deparse(golden, width.cutoff = 100), collapse = "\n"))
  )
  writeLines(out, "tests/testthat/golden-fingerprints.R")
  message("Wrote tests/testthat/golden-fingerprints.R")
}
